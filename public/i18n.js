const LANG_CODES = LANGUAGES.map(l => l.code);

function detectLang() {
  const saved = localStorage.getItem('lang');
  if (saved && LANG_CODES.includes(saved)) return saved;
  const nav = (navigator.language || 'en').toLowerCase();
  // Prefer an exact regional match (zh-TW) over the generic prefix (zh); codes
  // are mixed-case (zh-TW) while nav is lowercased, so compare case-insensitively.
  return LANG_CODES.find(c => c.toLowerCase() === nav)            // zh-tw → zh-TW
      || LANG_CODES.find(c => nav.startsWith(c.toLowerCase() + '-'))  // en-us → en
      || LANG_CODES.find(c => c.toLowerCase() === nav.split('-')[0])  // zh-cn → zh
      || 'en';
}

let currentLang = detectLang();

function langDir(lang = currentLang) {
  return (LANGUAGES.find(l => l.code === lang) || {}).dir || 'ltr';
}

function t(key, params = {}) {
  let s = LANG[currentLang]?.[key] || LANG.en[key] || key;
  for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, v);
  return s;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', langDir(lang));
}
